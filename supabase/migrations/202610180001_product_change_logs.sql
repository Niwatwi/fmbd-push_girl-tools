create table if not exists public.product_change_logs (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  changed_at timestamptz not null default now(),
  changed_by bigint,
  changed_by_name text not null default '',
  old_values jsonb not null,
  new_values jsonb not null
);

create index if not exists product_change_logs_product_changed_at_idx
  on public.product_change_logs (product_id, changed_at desc);

alter table public.product_change_logs enable row level security;
revoke all on public.product_change_logs from anon, authenticated;
grant all on public.product_change_logs to service_role;

create or replace function public.update_master_product_with_log(
  p_product_id bigint,
  p_product_data jsonb,
  p_changed_by bigint,
  p_changed_by_name text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  old_product public.products%rowtype;
  updated_product public.products%rowtype;
  audit_log_id bigint;
begin
  select *
    into old_product
    from public.products
   where id = p_product_id
   for update;

  if not found then
    raise exception 'ไม่พบสินค้า ID %', p_product_id;
  end if;

  update public.products
     set code = p_product_data->>'code',
         category_code = nullif(p_product_data->>'category_code', ''),
         category = p_product_data->>'category',
         sub_category = nullif(p_product_data->>'sub_category', ''),
         segment = nullif(p_product_data->>'segment', ''),
         company = nullif(p_product_data->>'company', ''),
         company_type = p_product_data->>'company_type',
         brand_type = nullif(p_product_data->>'brand_type', ''),
         brand = nullif(p_product_data->>'brand', ''),
         sub_brand = nullif(p_product_data->>'sub_brand', ''),
         pack_name = p_product_data->>'pack_name',
         descriptions = p_product_data->>'descriptions',
         barcode = p_product_data->>'barcode',
         img_front = nullif(p_product_data->>'img_front', ''),
         img_back = nullif(p_product_data->>'img_back', ''),
         img_left = nullif(p_product_data->>'img_left', ''),
         img_right = nullif(p_product_data->>'img_right', ''),
         img_top = nullif(p_product_data->>'img_top', ''),
         img_bottom = nullif(p_product_data->>'img_bottom', ''),
         is_active = coalesce((p_product_data->>'is_active')::boolean, true),
         imageurl = nullif(p_product_data->>'imageurl', ''),
         img_price_tag = nullif(p_product_data->>'img_price_tag', ''),
         img_planogram = nullif(p_product_data->>'img_planogram', ''),
         "Dimension" = nullif(p_product_data->>'Dimension', ''),
         sku_code = nullif(p_product_data->>'sku_code', '')
   where id = p_product_id
   returning * into updated_product;

  insert into public.product_change_logs (
    product_id,
    changed_by,
    changed_by_name,
    old_values,
    new_values
  ) values (
    p_product_id,
    p_changed_by,
    coalesce(nullif(p_changed_by_name, ''), 'Admin'),
    to_jsonb(old_product),
    to_jsonb(updated_product)
  )
  returning id into audit_log_id;

  return jsonb_build_object(
    'product', to_jsonb(updated_product),
    'log_id', audit_log_id
  );
end;
$$;

revoke all on function public.update_master_product_with_log(bigint, jsonb, bigint, text)
  from public, anon, authenticated;
grant execute on function public.update_master_product_with_log(bigint, jsonb, bigint, text)
  to service_role;
