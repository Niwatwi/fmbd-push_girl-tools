create table if not exists public.sales_pitch_videos (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  user_name text,
  store_code text not null,
  store_name text,
  account text,
  promotion_id bigint references public.promotions(id) on delete set null,
  campaign_title text,
  video_url text not null,
  storage_path text not null,
  mime_type text,
  file_size bigint,
  file_name text,
  recorded_at timestamptz not null default now()
);

create index if not exists sales_pitch_videos_promotion_idx
  on public.sales_pitch_videos (promotion_id, recorded_at desc);
create index if not exists sales_pitch_videos_account_idx
  on public.sales_pitch_videos (account, recorded_at desc);

-- เข้าถึงผ่าน service role (server actions) เท่านั้น
alter table public.sales_pitch_videos enable row level security;

