create table if not exists public.promotion_brief_media (
  id bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions(id) on delete cascade,
  media_type text not null check (media_type in ('VIDEO', 'DOCUMENT')),
  title text not null,
  media_url text not null,
  mime_type text,
  storage_path text,
  poster_url text,
  poster_path text,
  duration text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists promotion_brief_media_promotion_order_idx
  on public.promotion_brief_media (promotion_id, sort_order, id);

alter table public.promotion_brief_media enable row level security;

drop policy if exists "Public can view active promotion brief media"
  on public.promotion_brief_media;
create policy "Public can view active promotion brief media"
  on public.promotion_brief_media
  for select
  to anon, authenticated
  using (is_active = true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'promotion-briefs',
  'promotion-briefs',
  true,
  104857600,
  array['video/mp4', 'video/webm', 'image/jpeg', 'image/png', 'image/webp', 'application/pdf']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view promotion brief files" on storage.objects;
create policy "Public can view promotion brief files"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'promotion-briefs');
