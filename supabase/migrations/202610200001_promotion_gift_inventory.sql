alter table public.promotions
  add column if not exists gift_items jsonb not null default '[]'::jsonb;

alter table public.pg_daily_activity_reports
  add column if not exists promotion_gift_given jsonb not null default '{}'::jsonb;

create table if not exists public.promotion_gift_receipts (
  id bigint generated by default as identity primary key,
  promotion_id bigint not null references public.promotions(id) on delete cascade,
  gift_key text not null,
  store_code text not null,
  received_date date not null,
  quantity integer not null check (quantity > 0),
  created_by bigint,
  created_at timestamptz not null default now()
);

create index if not exists promotion_gift_receipts_inventory_idx
  on public.promotion_gift_receipts (promotion_id, store_code, gift_key, received_date);